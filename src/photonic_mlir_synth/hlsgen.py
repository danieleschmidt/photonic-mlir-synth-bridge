"""
PhotonicHLSGen - Verilog-style HLS code generator for silicon photonic circuits.

Generates hardware description pseudocode for Mach-Zehnder Interferometer (MZI)
meshes used in photonic neural network accelerators.
"""

import numpy as np


class PhotonicHLSGen:
    """
    High-Level Synthesis generator for silicon photonic AI accelerators.

    Produces Verilog-style hardware description modules for photonic
    components including MZI elements, meshes, and full neural layers.
    """

    def __init__(self):
        """Initialize the HLS generator."""
        self._module_count = 0
        self._indent = "  "

    def generate_header(self) -> str:
        """Generate standard Verilog file header comment block."""
        return (
            "// ============================================================\n"
            "// Photonic MLIR Synthesis Bridge - HLS Output\n"
            "// Silicon Photonic AI Accelerator\n"
            "// Auto-generated by PhotonicHLSGen\n"
            "// ============================================================\n"
            "// WARNING: This is synthesized HLS pseudocode.\n"
            "// Target: silicon photonic process (strip waveguide, 220nm SOI)\n"
            "// ============================================================\n"
        )

    def generate_footer(self) -> str:
        """Generate standard Verilog file footer comment block."""
        return (
            "\n"
            "// ============================================================\n"
            "// End of HLS synthesis output\n"
            "// ============================================================\n"
        )

    def generate_mzi_module(self, mzi_id: int, theta: float, phi: float) -> str:
        """
        Generate a Verilog-style module for a single MZI (Mach-Zehnder Interferometer).

        Args:
            mzi_id: Unique identifier for this MZI element
            theta: Phase shift in upper arm (radians)
            phi: Phase shift in lower arm (radians)

        Returns:
            Verilog-style module string for the MZI
        """
        cos_t = float(np.cos(theta / 2))
        sin_t = float(np.sin(theta / 2))
        phase_e = float(np.exp(1j * phi).real)  # real part of e^(j*phi)

        lines = [
            f"// MZI element mzi_{mzi_id}: theta={theta:.6f} rad, phi={phi:.6f} rad",
            f"module mzi_{mzi_id} (",
            f"  input  wire [31:0] in_upper,  // optical field upper port",
            f"  input  wire [31:0] in_lower,  // optical field lower port",
            f"  output wire [31:0] out_upper,",
            f"  output wire [31:0] out_lower",
            f");",
            f"  // Transfer matrix: [[cos(θ/2), j·sin(θ/2)], [j·sin(θ/2), cos(θ/2)]] · diag(1, e^jφ)",
            f"  parameter real COS_THETA_HALF = {cos_t:.8f};",
            f"  parameter real SIN_THETA_HALF = {sin_t:.8f};",
            f"  parameter real PHI_PHASE_REAL  = {phase_e:.8f};  // Re(e^jφ)",
            f"",
            f"  // Beam splitter 1 (50:50)",
            f"  wire [31:0] bs1_upper, bs1_lower;",
            f"  assign bs1_upper = COS_THETA_HALF * in_upper + SIN_THETA_HALF * in_lower;",
            f"  assign bs1_lower = SIN_THETA_HALF * in_upper - COS_THETA_HALF * in_lower;",
            f"",
            f"  // Phase shifter (lower arm)",
            f"  wire [31:0] phase_out;",
            f"  assign phase_out = PHI_PHASE_REAL * bs1_lower;",
            f"",
            f"  // Beam splitter 2 (50:50)",
            f"  assign out_upper = COS_THETA_HALF * bs1_upper + SIN_THETA_HALF * phase_out;",
            f"  assign out_lower = SIN_THETA_HALF * bs1_upper - COS_THETA_HALF * phase_out;",
            f"",
            f"endmodule  // mzi_{mzi_id}",
        ]
        return "\n".join(lines)

    def generate_mesh_module(self, name: str, size: int) -> str:
        """
        Generate a Verilog-style module for an MZI mesh.

        Uses a Clements decomposition layout for a unitary mesh of
        given size (size x size MZI network).

        Args:
            name: Module name
            size: Dimension of the mesh (number of input/output waveguides)

        Returns:
            Verilog-style module string for the MZI mesh
        """
        n_mzi = size * (size - 1) // 2  # MZIs for an N-port unitary

        # Generate random-ish but deterministic theta/phi for placeholder
        rng = np.random.default_rng(size)
        thetas = rng.uniform(0, 2 * np.pi, n_mzi)
        phis = rng.uniform(0, 2 * np.pi, n_mzi)

        lines = [
            f"// MZI Mesh module '{name}': {size}x{size} unitary, {n_mzi} MZI elements",
            f"// Clements decomposition layout",
            f"module {name} (",
        ]

        # Input/output ports
        for i in range(size):
            sep = "," if i < size - 1 else ""
            lines.append(f"  input  wire [31:0] in_{i}{sep}")
        for i in range(size):
            sep = "," if i < size - 1 else ""
            lines.append(f"  output wire [31:0] out_{i}{sep}")
        lines.append(");")
        lines.append("")
        lines.append(f"  // {n_mzi} MZI sub-modules (Clements layout)")
        lines.append("")

        # Instantiate MZIs
        for idx in range(n_mzi):
            lines.append(
                f"  mzi_{idx} #(.THETA({thetas[idx]:.6f}), .PHI({phis[idx]:.6f})) "
                f"u_mzi_{idx} ("
            )
            lines.append(f"    .in_upper(layer_{idx}_upper),")
            lines.append(f"    .in_lower(layer_{idx}_lower),")
            lines.append(f"    .out_upper(layer_{idx+1}_upper),")
            lines.append(f"    .out_lower(layer_{idx+1}_lower)")
            lines.append(f"  );")

        lines.append("")
        lines.append(f"endmodule  // {name}")
        return "\n".join(lines)

    def generate_layer(self, layer_name: str, in_size: int, out_size: int) -> str:
        """
        Generate a full photonic neural network layer.

        Combines an MZI mesh (unitary transform) with optical nonlinearity
        and optional wavelength routing.

        Args:
            layer_name: Name for this layer
            in_size: Number of input waveguide channels
            out_size: Number of output waveguide channels

        Returns:
            Verilog-style HLS string for the full photonic layer
        """
        mesh_size = max(in_size, out_size)

        lines = [
            f"// Photonic layer '{layer_name}': {in_size} inputs → {out_size} outputs",
            f"// Architecture: input_pad → MZI_mesh → photodetect → output_route",
            f"module {layer_name} (",
        ]

        for i in range(in_size):
            lines.append(f"  input  wire [31:0] in_{i},")
        for i in range(out_size):
            sep = "," if i < out_size - 1 else ""
            lines.append(f"  output wire [31:0] out_{i}{sep}")
        lines.append(");")
        lines.append("")
        lines.append(f"  // Pad inputs to mesh_size={mesh_size}")
        lines.append(f"  wire [31:0] padded [{mesh_size-1}:0];")
        for i in range(in_size):
            lines.append(f"  assign padded[{i}] = in_{i};")
        for i in range(in_size, mesh_size):
            lines.append(f"  assign padded[{i}] = 32'h0;  // zero pad")

        lines.append("")
        lines.append(f"  // Unitary MZI mesh transform")
        lines.append(f"  wire [31:0] mesh_out [{mesh_size-1}:0];")
        lines.append(
            f"  {layer_name}_mesh u_mesh (.in(padded), .out(mesh_out));"
        )

        lines.append("")
        lines.append(f"  // Optical intensity detection (|E|^2 nonlinearity)")
        lines.append(f"  wire [31:0] detected [{mesh_size-1}:0];")
        lines.append(f"  genvar gi;")
        lines.append(f"  generate")
        lines.append(f"    for (gi = 0; gi < {mesh_size}; gi = gi + 1) begin : detect")
        lines.append(f"      assign detected[gi] = mesh_out[gi] * mesh_out[gi];")
        lines.append(f"    end")
        lines.append(f"  endgenerate")

        lines.append("")
        lines.append(f"  // Route {out_size} outputs")
        for i in range(out_size):
            lines.append(f"  assign out_{i} = detected[{i}];")

        lines.append("")
        lines.append(f"endmodule  // {layer_name}")
        return "\n".join(lines)
